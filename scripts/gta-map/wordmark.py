"""
Writes the intro's wordmark, PERMITGUYS in Playfair Display Black (the face
of the homepage hero's name; SIL Open Font License), as SVG outlines, one
path per letter, to src/content/intro-wordmark.ts.

    python3 scripts/gta-map/wordmark.py path/to/PlayfairDisplay-Black.woff2

Needs fontTools (and brotli for a .woff2). After `npm run build`, the face
next/font downloads is in .next/static/media/ (the Latin subset, the one
whose name table says Playfair Display Black and that has every letter).
"""

import os
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
WORD = "PERMITGUYS"
# Letter-spacing in font units, opened up a little for a line drawing.
TRACKING = 60


def main(font_path):
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    upm = font["head"].unitsPerEm
    x = 0
    letters = []
    for ch in WORD:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
        # Font units are y-up; the SVG is y-down, with the baseline at the cap height.
        cap = font["OS/2"].sCapHeight
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, cap)))
        letters.append(pen.getCommands())
        x += hmtx[name][0] + TRACKING
    width = x - TRACKING
    # The ink's own box, so the drawing sits tight in its viewBox.
    bounds = BoundsPen(glyphs)
    x = 0
    for ch in WORD:
        name = cmap[ord(ch)]
        glyphs[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, font["OS/2"].sCapHeight)))
        x += hmtx[name][0] + TRACKING
    x0, y0, x1, y1 = bounds.bounds
    out = [
        "/**",
        " * The intro's wordmark (Preloader.tsx): PERMITGUYS in Playfair Display",
        " * Black, the face of the homepage hero's name (SIL Open Font License), as",
        " * outlines, one path per letter, in font units. Generated by",
        " * scripts/gta-map/wordmark.py: do not edit by hand.",
        " */",
        "",
        f'export const WORDMARK_VIEWBOX = "{round(x0) - 20} {round(y0) - 20} {round(x1 - x0) + 40} {round(y1 - y0) + 40}";',
        "",
        f"export const WORDMARK_LETTERS = {letters!r};".replace("'", '"'),
        "",
    ]
    with open(os.path.join(ROOT, "src", "content", "intro-wordmark.ts"), "w") as f:
        f.write("\n".join(out))
    print(width, upm, bounds.bounds)


if __name__ == "__main__":
    main(sys.argv[1])
