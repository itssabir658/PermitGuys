"""
The projects map's points (src/content/project-points.ts), from the firm's
Google My Maps map "Our Projects" (site.projectsMap.mid).

Reads the map's KML, geocodes each pin's address with OpenStreetMap's
Nominatim (one request a second, cached in --cache so a rerun only asks for
new pins), and writes the points blurred to their area: each is snapped to
a cell of about 500m and placed at a fixed pseudo-random spot inside it, so
the site never shows where a client lives. Addresses never leave this
script. Run it again when pins are added to the map:

    python3 scripts/project-map/build.py --cache /tmp/project-geocode.json
"""
import argparse, hashlib, json, os, re, time, urllib.parse, urllib.request

MID = "1TuO8AYFVvh5b1pRdq_TYlNBSngzpcEc"
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "content", "project-points.ts")
UA = {"User-Agent": "PermitGuys-website-build/1.0 (project map geocode)"}
CELL = 0.005  # degrees: about 550m north to south, 400m east to west at the GTA's latitude


def kml_addresses():
    url = f"https://www.google.com/maps/d/kml?mid={MID}&forcekml=1"
    text = urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60).read().decode()
    return [a.strip() for a in re.findall(r"<address>(.*?)</address>", text, re.S)]


def nominatim(text):
    url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode({"q": text, "format": "json", "limit": 1, "countrycodes": "ca"})
    for _ in range(3):
        try:
            hits = json.load(urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=20))
            return hits[0] if hits else None
        except Exception:
            time.sleep(3)
    return None


def geocode(address):
    """The address, then without its postal code, then without its first part (a unit or a name), then its town alone."""
    parts = [p.strip() for p in address.split(",")]
    tries = [address, re.sub(r"\b[A-Z]\d[A-Z] ?\d[A-Z]\d\b", "", address)]
    if len(parts) >= 3:
        tries += [", ".join(parts[1:]), parts[-3] + ", Ontario"]
    for level, text in enumerate(tries):
        hit = nominatim(text)
        time.sleep(1.1)
        if hit:
            return {"lat": float(hit["lat"]), "lon": float(hit["lon"]), "level": level}
    return None


def blur(address, lon, lat):
    """Snapped to its cell and moved to a fixed spot inside it, chosen from the address so reruns agree."""
    h = hashlib.sha256(address.encode()).digest()
    fx, fy = h[0] / 255, h[1] / 255
    x = (lon // CELL + 0.15 + 0.7 * fx) * CELL
    y = (lat // CELL + 0.15 + 0.7 * fy) * CELL
    return round(x, 4), round(y, 4)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", required=True, help="JSON cache of geocoded addresses (keep it out of the repository)")
    ap.add_argument("--kml", help="a saved KML instead of fetching the map")
    args = ap.parse_args()
    addresses = re.findall(r"<address>(.*?)</address>", open(args.kml).read(), re.S) if args.kml else kml_addresses()
    addresses = [a.strip() for a in addresses]
    cache = json.load(open(args.cache)) if os.path.exists(args.cache) else {}
    for a in addresses:
        if a not in cache:
            cache[a] = geocode(a)
            json.dump(cache, open(args.cache, "w"))
    points = sorted({blur(a, cache[a]["lon"], cache[a]["lat"]) for a in addresses if cache.get(a)})
    missed = sum(1 for a in addresses if not cache.get(a))
    with open(OUT, "w") as f:
        f.write("/**\n")
        f.write(" * The firm's client projects as points for the projects map\n")
        f.write(" * (ProjectsMap.tsx): [longitude, latitude], each blurred to an area of\n")
        f.write(" * about 500m so no client's address can be read from it. Generated by\n")
        f.write(" * scripts/project-map/build.py from the firm's Google My Maps map: do not\n")
        f.write(" * edit by hand.\n */\n")
        f.write(f"export const projectPoints: [number, number][] = {json.dumps([list(p) for p in points], separators=(',', ':'))};\n")
    print(f"{len(points)} points from {len(addresses)} pins; {missed} not found")


if __name__ == "__main__":
    main()
